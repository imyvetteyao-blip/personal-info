import { test, expect } from "@playwright/test";
import ExcelJS from "exceljs";
import { mockInventory, publishedInventory, field, addComponent } from "./fixture.mjs";
const name = "Sodium taurocholate hydrate";
const paste = async (page, value) => {
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.evaluate((text) => navigator.clipboard.writeText(text), value);
  await page.locator("#inventory-query").press("Control+V");
};
test("real clipboard paste finds the same chemical as typing, including copied line breaks and invisible characters", async ({ page }) => {
  await mockInventory(page, { current: publishedInventory({ name }) });
  await page.goto("#buffer");
  const query = page.locator("#inventory-query");
  await query.waitFor();
  await query.pressSequentially(name);
  await expect(page.locator(".inventory-results")).toContainText(name);
  await query.fill("");
  await paste(page, "\ufeffSodium\u00a0tauro\u200bcholate\r\nhydrate\t");
  await expect(query).toHaveValue(name);
  await expect(page.locator(".inventory-results")).toContainText(name);
  await query.fill("Sodium hydrate");
  await query.evaluate((input) => input.setSelectionRange(7, 7));
  await paste(page, "taurocholate ");
  await expect(query).toHaveValue(name);
  await expect(page.locator(".inventory-results")).toContainText(name);
  await query.fill("Unmatched chemical");
  await query.selectText();
  await paste(page, "DEMO\u2011001");
  await expect(page.locator(".inventory-results")).toContainText(name);
  await query.evaluate((input) => {
    input.value = "Sodium\u202ftaurocholate hydrate";
    input.dispatchEvent(new Event("change", { bubbles: true }));
  });
  await expect(page.locator(".inventory-results")).toContainText(name);
});
test("target mass calculates from µL preparation volume before observations and survives save, reopen and Excel export", async ({ page }) => {
  await mockInventory(page, { current: publishedInventory({ name }) });
  await page.goto("#buffer");
  await page.locator("#inventory-query").waitFor();
  await expect(field(page, "volumeUnit")).toHaveValue("mL");
  await addComponent(page);
  await field(page, "components.0.form").selectOption("solid");
  await field(page, "components.0.mw").fill("555.7");
  await field(page, "components.0.target").fill("14");
  const target = page.locator(".component-row .target-mass-cell");
  await target.getByRole("button", { name: "Set Target Volume" }).click();
  await expect(field(page, "volume")).toBeFocused();
  await field(page, "volumeUnit").selectOption("µL");
  await field(page, "volume").fill("100000");
  await expect(target).toHaveText("777.98");
  await expect(field(page, "components.0.actualMass")).toHaveValue("");
  await field(page, "components.0.target").fill("7");
  await expect(target).toHaveText("388.99");
  await field(page, "volume").fill("200000");
  await expect(target).toHaveText("777.98");
  await field(page, "components.0.mw").fill("100");
  await expect(target).toHaveText("140.00");
  await field(page, "components.0.mw").fill("555.7");
  await field(page, "name").fill("Automatic target recipe");
  await page.getByRole("button", { name: "Save Preparation Record" }).first().click();
  await page.reload();
  await page.getByRole("link", { name: "Records", exact: true }).click();
  await page.getByRole("button", { name: "Open", exact: true }).click();
  await expect(target).toHaveText("777.98");
  const event = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export Preparation Excel" }).click();
  const w = new ExcelJS.Workbook();
  await w.xlsx.readFile(await (await event).path());
  const s = w.getWorksheet("Preparation");
  expect(s.getCell("F15").value).toBeCloseTo(777.98, 9);
  expect(s.getCell("H15").value).toBeNull();
  expect(s.getCell("I15").value).toBeNull();
});
test("missing and invalid target inputs give an actionable prompt instead of assuming a mass", async ({ page }) => {
  await mockInventory(page);
  await page.goto("#buffer");
  await page.locator("#inventory-query").waitFor();
  await field(page, "volume").fill("100");
  await addComponent(page);
  await field(page, "components.0.mw").fill("");
  const target = page.locator(".component-row .target-mass-cell");
  await target.getByRole("button", { name: "Enter MW" }).click();
  await expect(field(page, "components.0.mw")).toBeFocused();
  await field(page, "components.0.mw").fill("555.7");
  await target.getByRole("button", { name: "Set Target Conc." }).click();
  await expect(field(page, "components.0.target")).toBeFocused();
  await field(page, "components.0.target").fill("14");
  await field(page, "volume").fill("0");
  await target.getByRole("button", { name: "Check inputs" }).click();
  await expect(page.locator("#detail-content")).toHaveValue(/Final buffer volume must be greater than zero/);
});
